const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const output=path.resolve(process.argv[2]||path.join(root,'..','Meu-Dinheiro-v38-Diagnostico-Corrigido.html'));
execFileSync(process.execPath,[path.join(__dirname,'gerar-html-design-v37.cjs'),output],{stdio:'pipe'});
const load=name=>fs.readFileSync(path.join(root,'preview-v38',name),'utf8');
const protect=source=>source.replace(/<\/script/gi,'<\\/script');
let html=fs.readFileSync(output,'utf8');
html=html.replace('</body>',`<script data-preview-v38="ui/versao.js">\n${protect(load('ui/versao.js'))}\n</script>\n<script data-preview-v38="ui/diagnostico.js">\n${protect(load('ui/diagnostico.js'))}\n</script>\n</body>`);
html=html.replace('<title>Meu Dinheiro — v37 Diagnóstico Unificado</title>','<title>Meu Dinheiro — v38 Diagnóstico Corrigido</title>');
fs.writeFileSync(output,html);
console.log(`Prévia completa v38: ${output} (${Buffer.byteLength(html)} bytes)`);
